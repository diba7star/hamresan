label{display:block;margin-top:10px;font-weight:600}
input{width:100%;box-sizing:border-box;padding:10px;border:1px solid #cbd5e1;border-radius:8px;margin-top:4px;font-size:15px}
button{background:#0f766e;color:#fff;border:0;border-radius:8px;padding:12px 22px;font-size:16px;cursor:pointer;margin-top:16px}
.err{background:#fee2e2;color:#7f1d1d;padding:10px 14px;border-radius:8px;margin:10px 0}
.ok{background:#ccfbf1;color:#134e4a;padding:10px 14px;border-radius:8px;margin:10px 0}
.muted{color:#64748b;font-size:13px}
.key{background:#f1f5f9;padding:8px 12px;border-radius:6px;direction:ltr;display:block;word-break:break-all;font-family:Consolas,monospace;margin:4px 0;font-size:16px}
.big{font-size:22px;font-weight:700;color:#0f766e}
</style>
</head>
<body>
<div class="card">
<h1>نصب مرکز همرسان</h1>
<p class="muted">«مرکز» فهرست محله‌هاست: شناسه هر محله و کلید عمومی مدیرش را نگه می‌دارد تا شناسه‌ها یکتا باشند. نشانی سرورها در آن ثبت نمی‌شود. هر گروه، شهر یا سازمان می‌تواند مرکز مستقل خودش را داشته باشد.</p>
<?php if ($problems): ?>
  <div class="err"><b>پیش از نصب این موارد را رفع کنید:</b><ul><?php foreach ($problems as $p) echo '<li>' . $h($p) . '</li>'; ?></ul></div>
<?php elseif ($result): ?>
  <div class="ok">مرکز «<?= $h($result['name']) ?>» نصب شد.</div>
  <h2>شناسه مرکز (به کاربران بدهید)</h2>
  <div class="key big"><?= $h($centerId) ?></div>
  <p class="muted">کاربران در برنامه: کاوش ← «افزودن مرکز» ← همین شناسه را وارد می‌کنند. مدیران محله هم همین را در نصب سرور محله به‌عنوان «نشانی مرکز» می‌دهند (برنامه و نصب‌کننده خودشان https:// و index.php را اضافه می‌کنند).</p>
  <h2>پنل مرکز (حذف شناسه‌های نامناسب)</h2>
  <div class="key"><?= $h($base) ?>/manage.php?token=<?= $h($result['token']) ?></div>
  <p class="muted">این لینک را ذخیره کنید؛ توکن داخل config.php است.</p>
  <div class="err"><b>حالا فایل install.php را از سرور حذف کنید.</b></div>
<?php elseif ($installed): ?>
  <div class="ok">این مرکز قبلاً نصب شده است. شناسه مرکز: <span class="key big"><?= $h($centerId) ?></span> فایل install.php را حذف کنید.</div>
<?php else: ?>
  <?php if (!$https): ?><div class="err">این صفحه با HTTPS باز نشده است. برنامه فقط به مرکزهای HTTPS وصل می‌شود؛ قبل از دادن شناسه به کاربران، گواهی SSL فعال کنید.</div><?php endif; ?>
  <?php if ($error): ?><div class="err"><?= $h($error) ?></div><?php endif; ?>
  <form method="post">
    <label>نام مرکز (فارسی)، مثلاً «مرکز محله‌های بندر»<input name="name" value="<?= $h($name) ?>" required></label>
    <p class="muted">شناسه مرکز به‌صورت خودکار از نشانی همین پوشه ساخته می‌شود: <b dir="ltr"><?= $h($centerId) ?></b></p>
    <button>نصب مرکز</button>
  </form>
<?php endif; ?>
</div>
</body>
