<?php
// Hamresan CENTER installer (a "center" is an independent directory of communities).
// Upload this folder, open this page once, then delete it.
declare(strict_types=1);
mb_internal_encoding('UTF-8');

$configFile = __DIR__ . '/config.php';
$h = fn($s) => htmlspecialchars((string) $s, ENT_QUOTES, 'UTF-8');
$problems = [];
if (PHP_VERSION_ID < 70200) $problems[] = 'PHP ۷.۲ یا بالاتر لازم است (نسخه فعلی ' . PHP_VERSION . ')';
if (!extension_loaded('pdo_sqlite')) $problems[] = 'افزونه pdo_sqlite فعال نیست';
if (!function_exists('sodium_crypto_sign_verify_detached') && !file_exists(__DIR__ . '/vendor/sodium_compat/autoload.php')) $problems[] = 'پوشه vendor/sodium_compat آپلود نشده';
if (!is_writable(__DIR__)) $problems[] = 'پوشه قابل نوشتن نیست (دسترسی ۷۵۵ یا ۷۰۵ بدهید)';

$https = isset($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off';
$host = $_SERVER['HTTP_HOST'] ?? 'localhost';
$path = rtrim(dirname($_SERVER['SCRIPT_NAME'] ?? '/'), '/\\');
$centerId = $host . $path;                       // what users type into the app
$base = ($https ? 'https' : 'http') . '://' . $centerId;

$installed = file_exists($configFile);
$result = null; $error = null;
$name = mb_substr(trim((string) ($_POST['name'] ?? '')), 0, 60);

if (!$installed && !$problems && $_SERVER['REQUEST_METHOD'] === 'POST') {
    if ($name === '') $error = 'نام مرکز لازم است';
    else {
        $token = rtrim(strtr(base64_encode(random_bytes(24)), '+/', 'Aa'), '=');
        $cfg = "<?php\n// Generated by install.php on " . date('c') . " — keep private\nreturn " .
            var_export(['center_name' => $name, 'center_id' => $centerId, 'admin_token' => $token, 'created' => date('c')], true) . ";\n";
        if (file_put_contents($configFile, $cfg, LOCK_EX) === false) $error = 'نوشتن config.php ممکن نشد';
        else { @chmod($configFile, 0600); $result = ['name' => $name, 'token' => $token]; $installed = true; }
    }
}
?>
<!doctype html>
<html lang="fa" dir="rtl">
<head>
<meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><meta name="robots" content="noindex">
